#pragma once
#include <llvm/IR/Module.h>

#include "solc/report/Finding.h"

namespace solc::analyzer {

// детектор отсутствующего контроля доступа (денежная ставка #1, AD-6).
//
// идея (честная, без угадывания намерения): понятие «owner» выводим из самого
// контракта — слот, значение которого где-то сравнивается с msg.sender, считаем
// привилегированным. функции, изменяющие привилегированное состояние БЕЗ такой
// проверки в своём теле, помечаем как отсутствие контроля доступа.
//
// граница (честно): проверка должна быть в ТЕЛЕ функции. модификаторы (onlyOwner)
// в текущем парсере пропускаются, поэтому контракты на модификаторах могут давать
// ложные срабатывания — это future work (нужна поддержка модификаторов).
class AccessControlDetector {
public:
    report::Findings analyze(const llvm::Module& m);
};

}  // namespace solc::analyzer
